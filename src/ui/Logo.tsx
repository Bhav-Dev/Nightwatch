import { useId } from 'react';
import Svg, { Circle, ClipPath, Defs, G, LinearGradient, Path, RadialGradient, Stop } from 'react-native-svg';

import { logoArt as art } from './logoArt';
import { colors } from './theme';

const stops = (colours: readonly string[]) =>
  colours.map((c, i) => <Stop key={c} offset={i / (colours.length - 1)} stopColor={c} />);

/** Room around the cell for its glow, in drawing units. */
const GLOW_ROOM = 110;

/**
 * The app's mark, as on the icon and the splash screen: the moon over a sound wave in a
 * honeycomb cell. Drawn from the icon's own shapes (`logoArt`, generated by `npm run icons`).
 */
export function Logo({ width = 200, glow = true }: { width?: number; glow?: boolean }) {
  const id = `logo${useId().replace(/[^a-zA-Z0-9]/g, '')}`;
  const pad = glow ? GLOW_ROOM : 0;
  const [x0, y0, x1, y1] = art.box;
  const [w, h] = [x1 - x0 + 2 * pad, y1 - y0 + 2 * pad];
  const [cx, cy] = [(x0 + x1) / 2, (y0 + y1) / 2];
  const { cell, glyph, moon, wave } = art;
  const [gx0, gy0, gx1, gy1] = glyph.box;
  const glyphTransform = `translate(${glyph.cx} ${glyph.cy}) scale(${glyph.s}) translate(${-(gx0 + gx1) / 2} ${-(gy0 + gy1) / 2})`;
  return (
    <Svg width={width} height={(width * h) / w} viewBox={`${x0 - pad} ${y0 - pad} ${w} ${h}`}>
      <Defs>
        <RadialGradient id={`${id}glow`} cx={cx} cy={cy} r={(y1 - y0) / 2 + pad} gradientUnits="userSpaceOnUse">
          <Stop offset={0.55} stopColor={colors.accent} stopOpacity={0.22} />
          <Stop offset={1} stopColor={colors.accent} stopOpacity={0} />
        </RadialGradient>
        <LinearGradient id={`${id}cell`} x1={cell.fillGradient[0]} y1={cell.fillGradient[1]} x2={cell.fillGradient[2]} y2={cell.fillGradient[3]} gradientUnits="userSpaceOnUse">
          {stops(cell.fill)}
        </LinearGradient>
        <LinearGradient id={`${id}honey`} x1={cell.honeyGradient[0]} y1={cell.honeyGradient[1]} x2={cell.honeyGradient[2]} y2={cell.honeyGradient[3]} gradientUnits="userSpaceOnUse">
          {stops(cell.honey)}
        </LinearGradient>
        <LinearGradient id={`${id}moon`} x1={moon.gradient[0]} y1={moon.gradient[1]} x2={moon.gradient[2]} y2={moon.gradient[3]} gradientUnits="userSpaceOnUse">
          {stops(moon.colours)}
        </LinearGradient>
        <LinearGradient id={`${id}wave`} x1={wave.gradient[0]} y1={wave.gradient[1]} x2={wave.gradient[2]} y2={wave.gradient[3]} gradientUnits="userSpaceOnUse">
          {stops(wave.colours)}
        </LinearGradient>
        <ClipPath id={`${id}above`}>
          <Path d={art.aboveWave} />
        </ClipPath>
      </Defs>
      {glow ? <Circle cx={cx} cy={cy} r={(y1 - y0) / 2 + pad} fill={`url(#${id}glow)`} /> : null}
      <Path d={cell.d} fill={`url(#${id}cell)`} />
      <Path d={cell.d} fill="none" stroke={`url(#${id}honey)`} strokeWidth={cell.stroke} strokeLinejoin="round" />
      <G transform={glyphTransform}>
        <Path d={moon.d} fill={`url(#${id}moon)`} clipPath={`url(#${id}above)`} />
        <Path d={wave.d} fill="none" stroke={`url(#${id}wave)`} strokeWidth={wave.width} strokeLinecap="round" />
      </G>
    </Svg>
  );
}
