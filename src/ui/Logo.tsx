import { useId } from 'react';
import Svg, { Circle, ClipPath, Defs, LinearGradient, Path, RadialGradient, Stop } from 'react-native-svg';

import { logoArt as art } from './logoArt';
import { colors } from './theme';

const stops = (colours: readonly string[]) =>
  colours.map((c, i) => <Stop key={c} offset={i / (colours.length - 1)} stopColor={c} />);

/** Room around the mark for the moon's glow, in drawing units. */
const GLOW_ROOM = 120;

/**
 * The app's mark, as on the icon and the splash screen: the moon rising over a sound wave, with
 * stars. Drawn from the icon's own shapes (`logoArt`, generated by `npm run icons`).
 */
export function Logo({ width = 220, glow = true }: { width?: number; glow?: boolean }) {
  const id = `logo${useId().replace(/[^a-zA-Z0-9]/g, '')}`;
  const pad = glow ? GLOW_ROOM : 0;
  const [x0, y0, x1, y1] = art.box;
  const [w, h] = [x1 - x0 + 2 * pad, y1 - y0 + 2 * pad];
  const [mx1, my1, mx2, my2] = art.moon.gradient;
  const [wx1, wy1, wx2, wy2] = art.wave.gradient;
  return (
    <Svg width={width} height={(width * h) / w} viewBox={`${x0 - pad} ${y0 - pad} ${w} ${h}`}>
      <Defs>
        <RadialGradient id={`${id}glow`} cx={art.moon.cx} cy={art.moon.cy} r={art.moon.r * 1.5} gradientUnits="userSpaceOnUse">
          <Stop offset={0} stopColor={colors.accent} stopOpacity={0.3} />
          <Stop offset={1} stopColor={colors.accent} stopOpacity={0} />
        </RadialGradient>
        <LinearGradient id={`${id}moon`} x1={mx1} y1={my1} x2={mx2} y2={my2} gradientUnits="userSpaceOnUse">
          {stops(art.moon.colours)}
        </LinearGradient>
        <LinearGradient id={`${id}wave`} x1={wx1} y1={wy1} x2={wx2} y2={wy2} gradientUnits="userSpaceOnUse">
          {stops(art.wave.colours)}
        </LinearGradient>
        <ClipPath id={`${id}above`}>
          <Path d={art.aboveWave} />
        </ClipPath>
      </Defs>
      {glow ? <Circle cx={art.moon.cx} cy={art.moon.cy} r={art.moon.r * 1.5} fill={`url(#${id}glow)`} /> : null}
      {art.stars.map((d) => (
        <Path key={d} d={d} fill={art.starColour} />
      ))}
      {art.dots.map((dot) => (
        <Circle key={`${dot.x},${dot.y}`} cx={dot.x} cy={dot.y} r={dot.r} fill={art.starColour} />
      ))}
      <Path d={art.moon.d} fill={`url(#${id}moon)`} clipPath={`url(#${id}above)`} />
      <Path d={art.wave.d} fill="none" stroke={`url(#${id}wave)`} strokeWidth={art.wave.width} strokeLinecap="round" />
    </Svg>
  );
}
